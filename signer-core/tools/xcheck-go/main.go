// Command xcheck-go writes ValidatorRegistrationV1 test vectors computed by
// attestantio/go-builder-client and go-eth2-client (fastssz). The C unit
// test compares sc_htr_validator_registration and the builder signing root
// against them, since consensus-spec-tests has no ssz_static vectors for
// this builder-specs container.
//
// Output, one registration per line:
//
//	fee_recipient gas_limit timestamp pubkey hash_tree_root signing_root
//
// signing_root uses DOMAIN_APPLICATION_BUILDER with GENESIS_FORK_VERSION
// 0x00000000 and a zero genesis_validators_root (mainnet builder domain).
package main

import (
	"fmt"
	"os"
	"time"

	apiv1 "github.com/attestantio/go-builder-client/api/v1"
	"github.com/attestantio/go-eth2-client/spec/bellatrix"
	"github.com/attestantio/go-eth2-client/spec/phase0"
)

// xorshift64 so the vectors are the same on every run.
type rng uint64

func (r *rng) next() uint64 {
	x := uint64(*r)
	x ^= x << 13
	x ^= x >> 7
	x ^= x << 17
	*r = rng(x)
	return x
}

func (r *rng) fill(b []byte) {
	for i := range b {
		b[i] = byte(r.next())
	}
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func main() {
	fd := &phase0.ForkData{CurrentVersion: phase0.Version{0, 0, 0, 0}}
	fdr, err := fd.HashTreeRoot()
	must(err)
	var domain phase0.Domain
	copy(domain[:4], []byte{0x00, 0x00, 0x00, 0x01})
	copy(domain[4:], fdr[:28])

	fmt.Printf("# generated by tools/xcheck-go; builder domain %x\n", domain[:])
	r := rng(0x243f6a8885a308d3)
	for i := 0; i < 64; i++ {
		var fee bellatrix.ExecutionAddress
		var pk phase0.BLSPubKey
		r.fill(fee[:])
		r.fill(pk[:])
		gas := r.next() % 100_000_000
		ts := r.next() % 4_000_000_000
		switch i {
		case 0: // all zero
			fee, pk, gas, ts = bellatrix.ExecutionAddress{}, phase0.BLSPubKey{}, 0, 0
		case 1: // all ones
			for j := range fee {
				fee[j] = 0xff
			}
			for j := range pk {
				pk[j] = 0xff
			}
			gas, ts = 30_000_000, 1_700_000_000
		}
		reg := &apiv1.ValidatorRegistration{
			FeeRecipient: fee,
			GasLimit:     gas,
			Timestamp:    time.Unix(int64(ts), 0),
			Pubkey:       pk,
		}
		root, err := reg.HashTreeRoot()
		must(err)
		sd := &phase0.SigningData{ObjectRoot: root, Domain: domain}
		sr, err := sd.HashTreeRoot()
		must(err)
		fmt.Printf("%x %d %d %x %x %x\n", fee[:], gas, ts, pk[:], root[:], sr[:])
	}
}
