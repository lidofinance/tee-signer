#!/usr/bin/env python3
"""Regression checks for distribution notices; no network or native build."""

import contextlib
import hashlib
import importlib.util
import io
import json
import os
from pathlib import Path
import tarfile
import tempfile
import unittest
import warnings
from unittest.mock import patch

spec = importlib.util.spec_from_file_location("bundle_licenses", Path(__file__).with_name("bundle-licenses.py"))
licenses = importlib.util.module_from_spec(spec)
spec.loader.exec_module(licenses)


class BundleTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.binary = self.root / "runner"
        self.binary.write_bytes(b"binary fixture")
        self.goroot = self.root / "go"
        (self.goroot / "src/vendor/example").mkdir(parents=True)
        (self.goroot / "LICENSE").write_text("Go BSD licence")
        (self.goroot / "src/vendor/example/LICENSE").write_text("vendored standard library notice")
        self.module = self.root / "module"
        self.module.mkdir()
        (self.module / "LICENSE").write_text("dependency licence")
        (self.module / "NOTICE").write_text("upstream attribution")
        self.info = {"GoVersion": "go1.26.0", "Settings": [], "Deps": [
            {"Path": "example.org/lib", "Version": "v1.0.0"},
        ]}
        env = patch.dict(os.environ, {}, clear=True)
        env.start()
        self.addCleanup(env.stop)
        mock = patch.object(licenses, "run", side_effect=self.run_command)
        mock.start()
        self.addCleanup(mock.stop)

    def run_command(self, *args):
        if args[1:3] == ("version", "-m"):
            return json.dumps(self.info)
        if args[1:] == ("env", "GOVERSION"):
            return "go1.26.0\n"
        if args[1:] == ("env", "GOROOT"):
            return str(self.goroot)
        if args[1:4] == ("mod", "download", "-json"):
            return json.dumps({"Dir": str(self.module)})
        raise AssertionError(args)

    def test_bundle_preserves_upstream_notice_and_is_repeatable(self):
        licenses.bundle(self.binary, {})
        out = Path(str(self.binary) + ".licenses")
        before = {p.name: p.read_bytes() for p in out.iterdir()}
        text = before["THIRD_PARTY_NOTICES"].decode()
        for required in ("upstream attribution", "dependency licence", "vendored standard library notice",
                         "example.org/lib@v1.0.0", "Go BSD licence"):
            self.assertIn(required, text)
        self.assertNotIn(str(self.root), text)
        self.assertEqual(before["LICENSE"], (licenses.ROOT / "LICENSE").read_bytes())
        licenses.bundle(self.binary, {})
        self.assertEqual(before, {p.name: p.read_bytes() for p in out.iterdir()})
        self.assertTrue(all(p.stat().st_mode & 0o777 == 0o644 for p in out.iterdir()))

    def test_missing_dependency_notices_fail_before_writing_bundle(self):
        for p in self.module.iterdir():
            p.unlink()
        with self.assertRaisesRegex(ValueError, "no licence or notice"):
            licenses.bundle(self.binary, {})
        self.assertFalse(Path(str(self.binary) + ".licenses").exists())

    def test_native_archive_without_reviewed_notices_is_rejected(self):
        self.info["Deps"][0]["Path"] = "github.com/pk910/hashtree-bindings"
        with self.assertRaisesRegex(ValueError, "native upstream notices"):
            licenses.bundle(self.binary, {})

    def test_external_local_replacement_is_rejected(self):
        self.info["Deps"][0]["Replace"] = {"Path": "../external"}
        with self.assertRaisesRegex(ValueError, "external local replacements"):
            licenses.bundle(self.binary, {})


LOCK = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "demo"
version = "1.2.3"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "{sum}"

[[package]]
name = "local"
version = "0.1.0"
dependencies = [
 "demo",
]
"""


@contextlib.contextmanager
def without_data_filter():
    """tarfile as on Python before 3.12, which has no extraction filters."""
    saved = getattr(tarfile, "data_filter", None)
    if saved is not None:
        del tarfile.data_filter
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", DeprecationWarning)
            yield
    finally:
        if saved is not None:
            tarfile.data_filter = saved


class CrateTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.home = self.root / "cargo-home"
        self.cache = self.home / "registry/cache/index.crates.io-0000000000000000"
        self.cache.mkdir(parents=True)
        self.archive = self.cache / "demo-1.2.3.crate"
        self.archive.write_bytes(self.crate(b"demo crate licence"))
        self.lock = self.root / "Cargo.lock"
        self.lock.write_text(LOCK.format(sum=hashlib.sha256(self.archive.read_bytes()).hexdigest()))

    @staticmethod
    def crate(licence, extra=None):
        out = io.BytesIO()
        with tarfile.open(fileobj=out, mode="w:gz") as tar:
            for name, body in (("demo-1.2.3/LICENSE-MIT", licence), ("demo-1.2.3/src/lib.rs", b"")):
                info = tarfile.TarInfo(name)
                info.size = len(body)
                tar.addfile(info, io.BytesIO(body))
            if extra is not None:
                tar.addfile(extra, io.BytesIO(b"x" * extra.size))
        return out.getvalue()

    def use(self, data):
        """Puts data in the cache as the demo archive, with its sha256 in the lock."""
        self.archive.write_bytes(data)
        self.lock.write_text(LOCK.format(sum=hashlib.sha256(data).hexdigest()))

    def test_lock_parser_without_tomllib(self):
        parsed = licenses.lock_crates(self.lock.read_text())
        with patch.dict("sys.modules", {"tomllib": None}):
            self.assertEqual(licenses.lock_crates(self.lock.read_text()), parsed)
        self.assertEqual([p[:2] for p in parsed], [("demo", "1.2.3")])

    def test_notices_come_from_the_checked_archive(self):
        sections = []
        licenses.add_crate_notices(sections, self.lock, self.home)
        self.assertEqual(sections, [("Rust crate demo-1.2.3 / LICENSE-MIT", "demo crate licence")])

    def test_changed_archive_is_rejected(self):
        self.archive.write_bytes(self.crate(b"another licence"))
        with self.assertRaisesRegex(ValueError, "differs from its sha256"):
            licenses.add_crate_notices([], self.lock, self.home)

    def test_changed_archive_in_a_second_index_folder_is_rejected(self):
        other = self.home / "registry/cache/index.crates.io-1111111111111111"
        other.mkdir()
        (other / "demo-1.2.3.crate").write_bytes(self.crate(b"another licence"))
        with self.assertRaisesRegex(ValueError, "differs from its sha256"):
            licenses.add_crate_notices([], self.lock, self.home)

    def test_notices_without_extraction_filter(self):
        # Python before 3.12 has no tarfile.data_filter.
        with without_data_filter():
            sections = []
            licenses.add_crate_notices(sections, self.lock, self.home)
        self.assertEqual(sections, [("Rust crate demo-1.2.3 / LICENSE-MIT", "demo crate licence")])

    def test_unsafe_members_are_rejected(self):
        def member(name, kind=tarfile.REGTYPE, link="", size=1):
            info = tarfile.TarInfo(name)
            info.type, info.linkname, info.size = kind, link, size
            return info
        cases = {
            "absolute name": member("/tmp/demo-escape"),
            "parent folder": member("demo-1.2.3/../demo-escape"),
            "symlink": member("demo-1.2.3/src/link.rs", tarfile.SYMTYPE, "/etc/passwd", 0),
            "hardlink": member("demo-1.2.3/src/hard.rs", tarfile.LNKTYPE, "demo-1.2.3/LICENSE-MIT", 0),
            "device": member("demo-1.2.3/dev", tarfile.CHRTYPE, size=0),
        }
        for what, info in cases.items():
            for filtered in (True, False):
                with self.subTest(what=what, filter=filtered):
                    self.use(self.crate(b"demo crate licence", info))
                    with contextlib.ExitStack() as stack:
                        if not filtered:
                            stack.enter_context(without_data_filter())
                        with self.assertRaisesRegex(ValueError, "a link, a special file or a path outside"):
                            licenses.add_crate_notices([], self.lock, self.home)

    def test_missing_archive_is_rejected(self):
        self.archive.unlink()
        with self.assertRaisesRegex(ValueError, "no archive"):
            licenses.add_crate_notices([], self.lock, self.home)


if __name__ == "__main__":
    unittest.main()
