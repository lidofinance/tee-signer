#!/usr/bin/env bash
# Self-test of scripts/nts-verify-crates.sh and of the fetch step of
# scripts/fetch-nts.sh, on a fixture cargo home with a fake Cargo.lock.
# Offline, no Docker (a stub stands in for it), no cargo: tar and sha256sum.
set -euo pipefail
SCRIPTS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VERIFY="$SCRIPTS/nts-verify-crates.sh"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
fails=0

# expect <exit code> <what> <command...>
expect() {
  local want="$1" what="$2" got=0
  shift 2
  "$@" >"$tmp/out" 2>&1 || got=$?
  if [ "$got" != "$want" ]; then
    echo "nts-verify-crates self-test: $what: exit $got, want $want" >&2
    sed 's/^/  /' "$tmp/out" >&2
    fails=$((fails + 1))
  fi
}

# crate <name> <version> <body> <out file>: a .crate archive (tar.gz).
crate() {
  local src="$tmp/src/$1-$2"
  rm -rf "$src"
  mkdir -p "$src/src"
  printf '[package]\nname = "%s"\nversion = "%s"\n' "$1" "$2" >"$src/Cargo.toml"
  printf '%s\n' "$3" >"$src/src/lib.rs"
  tar -czf "$4" -C "$tmp/src" "$1-$2"
}

mkdir -p "$tmp/good"
crate alpha 1.0.0 'pub fn a() {}' "$tmp/good/alpha-1.0.0.crate"
crate beta 2.0.0 'pub fn b() {}' "$tmp/good/beta-2.0.0.crate"
crate beta 2.0.0 'compile_error!("changed");' "$tmp/beta-changed.crate"
crate evil 1.0.0 'compile_error!("not in the lock");' "$tmp/evil-1.0.0.crate"
sum() { sha256sum "$1" | cut -d' ' -f1; }

LOCK="$tmp/Cargo.lock"
cat >"$LOCK" <<EOT
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "alpha"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "$(sum "$tmp/good/alpha-1.0.0.crate")"

[[package]]
name = "beta"
version = "2.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "$(sum "$tmp/good/beta-2.0.0.crate")"
dependencies = [
 "alpha",
]

[[package]]
name = "local"
version = "0.1.0"
dependencies = [
 "beta",
]
EOT

INDEX=registry/cache/index.crates.io-1949cf8c6b5b557f
OTHER=registry/cache/github.com-1ecc6299db9ec823

# home <name>: a fresh cargo home with both archives of the lock in INDEX.
home() {
  rm -rf "${tmp:?}/$1"
  mkdir -p "$tmp/$1/$INDEX"
  cp "$tmp"/good/*.crate "$tmp/$1/$INDEX/"
  echo "$tmp/$1"
}

h="$(home all)"
expect 0 "all archives present and matching" bash "$VERIFY" "$LOCK" "$h"

h="$(home missing)"
rm "$h/$INDEX/beta-2.0.0.crate"
expect 3 "one archive missing" bash "$VERIFY" "$LOCK" "$h"

h="$(home changed)"
cp "$tmp/beta-changed.crate" "$h/$INDEX/beta-2.0.0.crate"
expect 1 "one archive changed" bash "$VERIFY" "$LOCK" "$h"

h="$(home changed-and-missing)"
cp "$tmp/beta-changed.crate" "$h/$INDEX/beta-2.0.0.crate"
rm "$h/$INDEX/alpha-1.0.0.crate"
expect 1 "one archive changed, another missing" bash "$VERIFY" "$LOCK" "$h"

h="$(home cut)"
head -c 100 "$tmp/good/alpha-1.0.0.crate" >"$h/$INDEX/alpha-1.0.0.crate"
expect 1 "one archive cut short" bash "$VERIFY" "$LOCK" "$h"

h="$(home stray)"
cp "$tmp/evil-1.0.0.crate" "$h/$INDEX/"
expect 0 "an archive the lock does not name is ignored" bash "$VERIFY" "$LOCK" "$h"

h="$(home second)"
mkdir -p "$h/$OTHER"
cp "$tmp/good/alpha-1.0.0.crate" "$h/$OTHER/"
expect 0 "a second folder that lacks an archive" bash "$VERIFY" "$LOCK" "$h"

h="$(home second-changed)"
mkdir -p "$h/$OTHER"
cp "$tmp/beta-changed.crate" "$h/$OTHER/beta-2.0.0.crate"
expect 1 "a second folder with a changed archive" bash "$VERIFY" "$LOCK" "$h"

h="$(home split)"
mkdir -p "$h/$OTHER"
mv "$h/$INDEX/beta-2.0.0.crate" "$h/$OTHER/"
expect 0 "each archive in one of two folders" bash "$VERIFY" "$LOCK" "$h"

rm -rf "$tmp/empty"
mkdir -p "$tmp/empty"
expect 3 "a cargo home without a registry cache" bash "$VERIFY" "$LOCK" "$tmp/empty"

# Copy mode: only the lock's archives are copied, into the same folder names.
h="$(home copy)"
cp "$tmp/evil-1.0.0.crate" "$h/$INDEX/"
mkdir -p "$h/$OTHER" "$h/registry/index/x" "$h/registry/src/x"
cp "$tmp/good/alpha-1.0.0.crate" "$tmp/evil-1.0.0.crate" "$h/$OTHER/"
echo junk >"$h/registry/index/x/alpha"
echo junk >"$h/registry/src/x/lib.rs"
expect 0 "copy mode" bash "$VERIFY" "$LOCK" "$h" "$tmp/copy-new"
got="$(cd "$tmp/copy-new" && find . -type f | LC_ALL=C sort)"
want="./$OTHER/alpha-1.0.0.crate
./$INDEX/alpha-1.0.0.crate
./$INDEX/beta-2.0.0.crate"
if [ "$got" != "$want" ]; then
  echo "nts-verify-crates self-test: copy mode copied:" >&2
  echo "$got" >&2
  fails=$((fails + 1))
fi

h="$(home copy-changed)"
cp "$tmp/beta-changed.crate" "$h/$INDEX/beta-2.0.0.crate"
expect 1 "copy mode with a changed archive" bash "$VERIFY" "$LOCK" "$h" "$tmp/copy-changed-new"

# fetch-nts.sh on a copy of the scripts with the fixture lock. The docker stub
# says the toolchain image exists and plays cargo fetch: it copies
# $FAKE_FETCH, if set, into the mounted cargo home and leaves a mark.
root="$tmp/root"
mkdir -p "$root/scripts" "$root/bin"
cp "$SCRIPTS/common.sh" "$SCRIPTS/fetch-nts.sh" "$VERIFY" "$root/scripts/"
rust="$root/trusted-time/rust"
for d in . core nostd-check; do
  mkdir -p "$rust/$d/src"
  : >"$rust/$d/Cargo.toml"
done
cp "$LOCK" "$rust/Cargo.lock"
printf '# test\nalpha 1.0.0\nbeta 2.0.0\n' >"$rust/crates.allow"
cat >"$root/bin/docker" <<'EOT'
#!/usr/bin/env bash
[ "$1" = run ] || exit 0
: >"$FAKE_MARK"
while [ $# -gt 0 ]; do
  case "$1" in -v) case "$2" in *:/tmp/cargo-home) home="${2%:/tmp/cargo-home}" ;; esac ;; esac
  shift
done
[ -z "${FAKE_FETCH:-}" ] || cp -r "$FAKE_FETCH/." "$home/"
EOT
chmod +x "$root/bin/docker"
cache="$root/build/nts/cargo-home"
export FAKE_MARK="$tmp/docker-ran"
fetch=(env PATH="$root/bin:$PATH" bash "$root/scripts/fetch-nts.sh")

rm -rf "$cache" "$FAKE_MARK"
mkdir -p "$cache/$INDEX" "$cache/registry/src/x"
cp "$tmp/good/alpha-1.0.0.crate" "$cache/$INDEX/"
mkdir -p "$tmp/fetched/$INDEX"
cp "$tmp/good/beta-2.0.0.crate" "$tmp/fetched/$INDEX/"
expect 0 "fetch-nts.sh fetches a missing archive" env FAKE_FETCH="$tmp/fetched" "${fetch[@]}"
if [ ! -f "$FAKE_MARK" ] || [ -e "$cache/registry/src" ]; then
  echo "nts-verify-crates self-test: fetch-nts.sh did not fetch or did not drop registry/src" >&2
  fails=$((fails + 1))
fi

rm -rf "$cache" "$FAKE_MARK"
mkdir -p "$cache/$INDEX" "$cache/$OTHER"
cp "$tmp/good/alpha-1.0.0.crate" "$cache/$OTHER/"
expect 3 "fetch-nts.sh when cargo fetch adds nothing" "${fetch[@]}"
grep -q "remove $cache " "$tmp/out" ||
  { echo "nts-verify-crates self-test: fetch-nts.sh does not say to remove the cache" >&2; sed 's/^/  /' "$tmp/out" >&2; fails=$((fails + 1)); }

rm -rf "$cache" "$FAKE_MARK"
mkdir -p "$cache/$INDEX"
cp "$tmp/good/alpha-1.0.0.crate" "$cache/$INDEX/"
cp "$tmp/beta-changed.crate" "$cache/$INDEX/beta-2.0.0.crate"
expect 1 "fetch-nts.sh with a changed archive" "${fetch[@]}"
[ ! -e "$FAKE_MARK" ] ||
  { echo "nts-verify-crates self-test: fetch-nts.sh ran cargo with a changed archive in the cache" >&2; fails=$((fails + 1)); }

[ "$fails" = 0 ] || { echo "nts-verify-crates self-test: $fails failed" >&2; exit 1; }
echo "nts-verify-crates self-test: ok"
